const LANGS = { en: null, fr: FR };
export const LANGUAGES = [["en", "English"], ["fr", "Français"]];
const SKIP = "PRE, CODE, TEXTAREA, SCRIPT, STYLE, .console-out, .console-found, .mono, [data-no-translate]";
const ATTRS = ["placeholder", "aria-label", "title"];
let table = null;
let observer = null;

export function currentLanguage() {
  try { return localStorage.getItem("hearth.lang") || (navigator.language || "en").slice(0, 2); } catch { return "en"; }
}

function translateText(node) {
  const raw = node.nodeValue;
  const key = raw.trim();
  if (!key || !(key in table) || table[key] === key) return;
  node.nodeValue = raw.replace(key, table[key]);  // the result is never a key again (see below)
}

function translateElement(el) {
  if (el.closest?.(SKIP)) return;
  for (const attr of ATTRS) {
    const v = el.getAttribute?.(attr);
    if (v && v.trim() in table && table[v.trim()] !== v.trim()) el.setAttribute(attr, table[v.trim()]);
  }
  const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
    acceptNode: (n) => (n.nodeType === 1 && n.matches(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    if (n.nodeType === 3) translateText(n);
    else for (const attr of ATTRS) {
      const v = n.getAttribute(attr);
      if (v && v.trim() in table && table[v.trim()] !== v.trim()) n.setAttribute(attr, table[v.trim()]);
    }
  }
}

export function startTranslation() {
  const lang = currentLanguage();
  table = LANGS[lang] || null;
  document.documentElement.lang = table ? lang : "en";
  if (!table) return;
  translateElement(document.body);
  observer = new MutationObserver((mutations) => {
    for (const m of mutations) {
      if (m.type === "characterData") { if (!m.target.parentElement?.closest(SKIP)) translateText(m.target); continue; }
      for (const n of m.addedNodes) {
        if (n.nodeType === 3) { if (!n.parentElement?.closest(SKIP)) translateText(n); } else if (n.nodeType === 1) translateElement(n);
      }
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}

export function setLanguage(lang) {
  try { localStorage.setItem("hearth.lang", lang); } catch { /* storage blocked */ }
  location.reload();  // strings are swapped as they render; a fresh page is the simple, complete switch
}

export function setTheme(pref) {
  try { localStorage.setItem("hearth.theme", pref); } catch { /* storage blocked */ }
  const light = pref === "light" || (pref === "system" && matchMedia("(prefers-color-scheme: light)").matches);
  document.documentElement.dataset.theme = light ? "light" : "dark";
}

export function currentTheme() {
  try { return localStorage.getItem("hearth.theme") || "dark"; } catch { return "dark"; }
}
